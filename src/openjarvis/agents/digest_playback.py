"""Speak a scheduled morning digest aloud once its run finishes (D-013).

Playback lives here, not in the agent, so web/API requests and
``jarvis digest --fresh`` (which plays on its own) never trigger it, and the
generic scheduler never has to know about digests or audio.
"""

from __future__ import annotations

import logging
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Optional

from openjarvis.agents.digest_store import DigestStore
from openjarvis.core.config import load_config
from openjarvis.core.events import EventBus, EventType
from openjarvis.speech.playback import play_audio

logger = logging.getLogger(__name__)

_DIGEST_AGENT = "morning_digest"


def _autoplay_from_config() -> bool:
    return bool(load_config().digest.autoplay)


def _daemon_thread(target: Callable[..., Any], *args: Any) -> None:
    # Daemon so a long clip never blocks scheduler shutdown.
    threading.Thread(
        target=target, args=args, daemon=True, name="digest-autoplay"
    ).start()


class DigestAutoplay:
    """Listener that plays the fresh digest audio after a scheduled run.

    Plays only when the run succeeded, the agent is ``morning_digest``,
    ``digest.autoplay`` is on (read per event, so no restart is needed), and
    the newest stored digest was generated during this run and has an audio
    file. Never raises into the event publisher.
    """

    def __init__(
        self,
        *,
        autoplay_enabled: Callable[[], bool] = _autoplay_from_config,
        open_store: Callable[[], Any] = DigestStore,
        play: Callable[[str], Any] = play_audio,
        spawn: Callable[..., None] = _daemon_thread,
    ) -> None:
        self._autoplay_enabled = autoplay_enabled
        self._open_store = open_store
        self._play = play
        self._spawn = spawn

    def attach(self, bus: EventBus) -> None:
        bus.subscribe(EventType.SCHEDULER_TASK_END, self.on_task_end)

    def on_task_end(self, event: Any) -> None:
        try:
            data = getattr(event, "data", None) or {}
            if not data.get("success") or data.get("agent") != _DIGEST_AGENT:
                return
            if not self._autoplay_enabled():
                return
            audio = self._fresh_audio(data.get("started_at"))
            if audio is None:
                logger.info("Scheduled digest finished without fresh audio")
                return
            logger.info("Playing scheduled digest audio %s", audio)
            self._spawn(self._play, str(audio))
        except Exception:
            logger.exception("Digest autoplay failed")

    def _fresh_audio(self, started_at: Optional[str]) -> Optional[Path]:
        """The newest digest's audio file if it was generated by this run."""
        if not started_at:
            return None
        started = datetime.fromisoformat(started_at)
        if started.tzinfo is None:
            started = started.replace(tzinfo=timezone.utc)
        store = self._open_store()
        try:
            artifact = store.get_latest()
        finally:
            store.close()
        if artifact is None:
            return None
        # generated_at is naive local time; astimezone() interprets it as such.
        if artifact.generated_at.astimezone(timezone.utc) < started:
            return None
        # Path("") (failed TTS) renders as "." and exists(), so require a file.
        if not artifact.audio_path.is_file():
            return None
        return artifact.audio_path


__all__ = ["DigestAutoplay"]
